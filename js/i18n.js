/* ---------- helpers ---------- */
window.getLang = function () {
  return localStorage.getItem('ptr_lang') || 'bn';
};
window.T = function (key) {
  const lang = window.getLang();
  return (window.I18N[lang] && window.I18N[lang][key]) || window.I18N.bn[key] || key;
};
/* সংখ্যা → বাংলা ডিজিট কনভার্সন (bn ভাষায়) */
window.num = function (value) {
  const n = String(value);
  if (window.getLang() !== 'bn') return n;
  const bn = { '0': '০', '1': '১', '2': '২', '3': '৩', '4': '৪', '5': '৫', '6': '৬', '7': '৭', '8': '৮', '9': '৯' };
  return n.replace(/[0-9]/g, d => bn[d]);
};
/* সারা পাতার data-i18n / data-ph এলিমেন্ট আপডেট */
window.applyI18n = function () {
  const lang = window.getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const txt = window.T(el.getAttribute('data-i18n'));
    if (txt) el.textContent = txt;
  });
  document.querySelectorAll('[data-ph]').forEach(el => {
    el.setAttribute('placeholder', window.T(el.getAttribute('data-ph')));
  });
  const lbl = document.getElementById('langLabel');
  if (lbl) lbl.textContent = lang === 'bn' ? 'EN' : 'BN';
};
